export function getVocabBySubtopic(subtopicId: VocabSubtopicId): VocabItem[] {
  if (subtopicId === 'all') return WAREHOUSE_VOCABULARY;
  const meta = VOCAB_SUBTOPICS.find((s) => s.id === subtopicId);
  if (!meta) return WAREHOUSE_VOCABULARY;
  const catSet = new Set(meta.categories);
  return WAREHOUSE_VOCABULARY.filter((v) => catSet.has(v.category));
}

/**
 * Selects a balanced 25-word Daily Sprint deck prioritized by unlearned words first,
 * auto-renewing daily and rotating infinitely with batchSeed so learners can drill unlimited batches.
 */
export function buildDailyVocabDeck(
  learnedVocabIds: string[],
  partFilter?: number,
  targetCount = VOCAB_DAILY_TARGET,
  subtopicId: VocabSubtopicId = 'all',
  batchSeed = 0,
): VocabItem[] {
  let pool = getVocabBySubtopic(subtopicId);
  if (partFilter) {
    pool = pool.filter((v) => v.partNumber === partFilter);
  }

  const learnedSet = new Set(learnedVocabIds);
  const unlearned = pool.filter((v) => !learnedSet.has(v.id));
  const learned = pool.filter((v) => learnedSet.has(v.id));

  // Stable rotation by day-of-year + unlimited user batchSeed
  const now = new Date();
  const dayIndex = Math.floor(now.getTime() / 86_400_000);
  const shift = dayIndex * 7 + batchSeed * targetCount;

  const rotate = <T,>(arr: T[], step: number): T[] => {
    if (arr.length === 0) return arr;
    const offset = ((step % arr.length) + arr.length) % arr.length;
    return [...arr.slice(offset), ...arr.slice(0, offset)];
  };

  const combined = [...rotate(unlearned, shift), ...rotate(learned, shift)];
  return combined.slice(0, Math.min(targetCount, combined.length));
}
